        $errors[] = 'กรุณากรอกชื่อผู้ดูแลระบบ';
    }
    if (!filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'อีเมลผู้ดูแลระบบไม่ถูกต้อง';
    }
    if (strlen($adminPass) < 8) {
        $errors[] = 'รหัสผ่านผู้ดูแลระบบต้องมีอย่างน้อย 8 ตัวอักษร';
    }

    // Test connection (server only) and create database.
    if (!$errors) {
        $err = Database::testConnection($db, false);
        if ($err !== null) {
            $errors[] = 'เชื่อมต่อฐานข้อมูลไม่สำเร็จ: ' . $err;
        }
    }

    if (!$errors) {
        try {
            $server = Database::connect($db, false);
            $server->exec("CREATE DATABASE IF NOT EXISTS `{$db['name']}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");

            // Persist config, then boot the app connection from it.
            $appKey = ($existing['app_key'] ?? '') ?: bin2hex(random_bytes(32));
            if (!write_config($db, $app, $appKey)) {
                throw new RuntimeException('เขียนไฟล์ config/config.php ไม่ได้ — ตรวจสอบสิทธิ์การเขียนโฟลเดอร์ config/');
            }
            Config::load(CONFIG_PATH);
            date_default_timezone_set($app['timezone']);
            $pdo = Database::instance();

            if ($fresh) {
                drop_all($pdo);
            }

            // Schema + seed.
            (new Migrator($pdo))->migrate();
            seed_packages((int) $app['unit_days']);
            User::upsertAdmin($adminEmail, $adminPass, $adminName);
            if ($withDemo) {
                seed_demo((int) $app['unit_days']);
            }

            $done = true;
        } catch (\Throwable $e) {
            $errors[] = 'ติดตั้งไม่สำเร็จ: ' . $e->getMessage();
        }
    }
}

