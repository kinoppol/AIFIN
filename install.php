        'unit_days' => max(1, (int) ($_POST['unit_days'] ?? 30)),
    ];
    $adminName  = trim($_POST['admin_name'] ?? '');
    $adminEmail = trim($_POST['admin_email'] ?? '');
    $adminPass  = (string) ($_POST['admin_pass'] ?? '');
    $fresh      = !empty($_POST['fresh']);
    $withDemo   = !empty($_POST['demo']);

    // Validate.
