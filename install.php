/** Write config/config.php from the collected values. */
function write_config(array $db, array $app, string $appKey): bool
{
    $data = [
        'app' => [
            'name'                 => $app['name'],
            'env'                  => 'production',
            'debug'                => false,
            'timezone'             => $app['timezone'],
            'unit_days'            => (int) $app['unit_days'],
            'contract_months'      => 12,
            'max_extension_months' => 6,
        ],
        'db'      => $db,
        'app_key' => $appKey,
    ];
    $php = "<?php\n// Generated by install.php on " . date('c') . ". Do not commit.\nreturn "
         . var_export($data, true) . ";\n";
    if (!is_dir(dirname(CONFIG_PATH))) {
        @mkdir(dirname(CONFIG_PATH), 0775, true);
    }
    return (bool) file_put_contents(CONFIG_PATH, $php);
}

/** Drop every app table (FK-safe) for a fresh install. */
function drop_all(\PDO $pdo): void
{
    $pdo->exec('SET FOREIGN_KEY_CHECKS=0');
    foreach (['extension_requests','redemptions','unit_ledger','contracts','packages','users','settings','migrations'] as $t) {
        $pdo->exec("DROP TABLE IF EXISTS `{$t}`");
    }
    $pdo->exec('SET FOREIGN_KEY_CHECKS=1');
}

/** Seed the default sellable packages (idempotent by code). */
function seed_packages(int $unitDays): void
{
    $defaults = [
        ['starter', 'Starter', 'ลูกค้าบุคคล / ทีมเล็ก', 12, 750, 690, null, 'active', 1],
        ['team', 'Team', 'ทีม 5–20 คน', 60, 750, 630, 'ยอดนิยม', 'promo', 2],
        ['scale', 'Scale', 'องค์กรขนาดกลาง', 240, 750, 550, '-20%', 'active', 3],
        ['midyear', 'Mid-Year Boost', 'ส่วนลดเฉพาะช่วง · จำกัด 200 สัญญา', 60, 630, 499, 'โปรฯ', 'promo', 4],
    ];
    foreach ($defaults as [$code, $name, $note, $units, $list, $sale, $promo, $status, $sort]) {
        if (Package::findByCode($code)) {
            continue;
        }
        Package::insert([
            'code' => $code, 'name' => $name, 'note' => $note, 'units' => $units,
            'unit_days' => $unitDays, 'list_price' => $list, 'sale_price' => $sale,
            'promo_label' => $promo, 'status' => $status, 'sort_order' => $sort,
        ]);
    }
}

/** Optional demo data so the admin dashboard isn't empty. */
function seed_demo(int $unitDays): void
{
    if (User::findByEmail('demo@sinnovate.co')) {
        return; // already seeded
    }
    $svc = new App\Services\ContractService();
    $uid = User::create('demo@sinnovate.co', 'demo1234', 'บริษัท ซินโนเวท จำกัด (เดโม)', 'customer');
    $scale = Package::findByCode('scale');
    $cid = $svc->purchase($uid, 'บริษัท ซินโนเวท จำกัด (เดโม)', 240, (int) ($scale['sale_price'] ?? 550), (int) ($scale['id'] ?? null));
    // A successful redemption (bound seat) and a pending one.
    $r1 = $svc->redeem($cid, 'ops@sinnovate.co', 12);
    $svc->setRedemptionStatus($r1, 'success');
    $svc->redeem($cid, 'data@sinnovate.co', 6);
    // A pending extension request.
    $svc->requestExtension($cid, 2, 'ขยายทีมช้ากว่าแผน ขอใช้โควตาที่เหลือ');
}

